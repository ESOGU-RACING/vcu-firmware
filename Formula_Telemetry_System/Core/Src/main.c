/**
  * @brief  Her 1 ms'de bir donanım tarafından çağrılan kritik pedal kesmesi (T11.8)
  */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM3)
    {
        // CH0 (PB1): 1 ms referans kare dalgası (500 Hz)
        HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_1);

        // 1. Pedal yüzdelerini hesapla
        apps1_pct = Pedal_Normalize(sim_raw_apps1, false);
        apps2_pct = Pedal_Normalize(sim_raw_apps2, true);

        // 2. T11.8 Plausibility kontrolü yap ve röleyi sür
        if (Safety_EvaluateT11_8(apps1_pct, apps2_pct))
        {
            HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_SET);   // PB0 -> 3.3V (Sürüş İzni)
            tx_telemetry.error_code &= ~ERR_APPS_PLAUSIBILITY;
        }
        else
        {
            HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET); // PB0 -> 0V (Röleyi Aç)
            tx_telemetry.error_code |= ERR_APPS_PLAUSIBILITY;
        }
    }
}


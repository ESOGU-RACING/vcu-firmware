/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/
  HAL_Init();
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_USART1_UART_Init();
  MX_ADC1_Init();
  MX_ADC2_Init();
  MX_FDCAN1_Init();
  MX_TIM3_Init();

  /* USER CODE BEGIN 2 */
  Telemetry_Init();
  Pedal_Init();
  Safety_Init();
  Simulation_Init(&sim_state);

  // Başlangıçta Safe State devresini aktif yap (3.3V Sürüş İzni)
  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_SET);

  // TIM3 1 ms Donanımsal Emniyet Kesmesini Başlat
  HAL_TIM_Base_Start_IT(&htim3);
  /* USER CODE END 2 */

  /* Initialize led */
  BSP_LED_Init(LED_GREEN);

  /* Initialize USER push-button */
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Initialize COM1 port */
  BspCOMInit.BaudRate   = 115200;
  BspCOMInit.WordLength = COM_WORDLENGTH_8B;
  BspCOMInit.StopBits   = COM_STOPBITS_1;
  BspCOMInit.Parity     = COM_PARITY_NONE;
  BspCOMInit.HwFlowCtl  = COM_HWCONTROL_NONE;
  if (BSP_COM_Init(COM1, &BspCOMInit) != BSP_ERROR_NONE)
  {
    Error_Handler();
  }

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    // 50 ms (20 Hz) Asenkron DMA Telemetri Gönderim Döngüsü
    if (HAL_GetTick() - last_tx_time >= TELEMETRY_PERIOD_MS)
    {
        last_tx_time = HAL_GetTick();

        // 1. Simülasyon adımını ilerlet
        Simulation_Step(&sim_state);

        // 2. DMA hattı boşsa paketi hazırla ve gönder
        if (dma_tx_busy == 0)
        {
            Telemetry_PrepareFrame(sim_state.rpm, (uint8_t)sim_state.speed,
                                   sim_state.gear, sim_state.tps);
            dma_tx_busy = 1;

            HAL_UART_Transmit_DMA(&huart1, tx_raw_buf, sizeof(tx_raw_buf));
            HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5);
        }
    }
  }
  /* USER CODE END 3 */
}

